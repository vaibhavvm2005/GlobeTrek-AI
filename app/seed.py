def seed_experiences(cat_map: dict[str, Category]):
    """Populate at least 11 experiences per category (88 total) and active ticket tiers."""
    print("Checking and seeding global experiences (10+ per category)...")

    for item in EXPERIENCES_DATA:
        cat_slug = item["category_slug"]
        cat = cat_map.get(cat_slug)
        if not cat:
            continue

        existing = Experience.query.filter_by(slug=item["slug"]).first()
        if existing:
            continue

        exp = Experience(
            experience_name=item["name"],
            slug=item["slug"],
            category_id=cat.id,
            country=item["country"],
            city=item["city"],
            location=item.get("location", f"{item['city']}, {item['country']}"),
            description=item["description"],
            image_url=item["image_url"],
            gallery_images=json.dumps([item["image_url"]]),
            ticket_price=item["ticket_price"],
            rating=item["rating"],
            review_count=item["review_count"],
            availability=item["availability"],
            booking_enabled=item.get("booking_enabled", True),
            is_featured=item.get("is_featured", False),
            event_date=item.get("event_date"),
            opening_hours=item.get("opening_hours", "09:00 – 18:00"),
        )
        db.session.add(exp)
        db.session.flush()

        # Create active ticket tiers for bookable experiences
        if exp.booking_enabled:
            tt1 = TicketType(
                experience_id=exp.id,
                name="General Admission Pass",
                price=exp.ticket_price,
                quantity_total=exp.availability,
                max_per_booking=10,
                description=f"Standard admission pass to {exp.experience_name}.",
            )
            tt2 = TicketType(
                experience_id=exp.id,
                name="Priority Fast-Track / VIP Access",
                price=round(exp.ticket_price * 1.5, 2),
                quantity_total=max(20, int(exp.availability * 0.25)),
                max_per_booking=6,
                description=f"Skip-the-line priority admission pass to {exp.experience_name}.",
            )
            db.session.add_all([tt1, tt2])

    db.session.commit()
    print(f"Total experiences in database: {Experience.query.count()} across {Category.query.count()} categories.")


